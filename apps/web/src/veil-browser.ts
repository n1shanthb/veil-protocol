export function parseFieldDecimal(decStr: string | number | bigint, modulus: bigint, label: string): string {
  if (typeof decStr === "string" && !/^(0|[1-9][0-9]*)$/.test(decStr)) {
    throw new Error(`${label}: invalid decimal integer`);
  }
  const n = BigInt(decStr);
  if (n < 0n || n >= modulus) {
    throw new Error(`${label}: non-canonical field element`);
  }
  return n.toString(16).padStart(64, "0");
}

export function validateAndConvertVK(vk: any) {
  if (!vk || vk.protocol !== "groth16") throw new Error(`Unsupported protocol: ${vk?.protocol}`);
  if (vk.curve !== "bn128" && vk.curve !== "bn254") throw new Error(`Unsupported curve: ${vk?.curve}`);
  if (!Array.isArray(vk.IC) || vk.IC.length === 0) throw new Error("Missing IC array");
  const nPublic = vk.IC.length - 1;
  if (typeof vk.nPublic === "number" && vk.nPublic !== nPublic) {
    throw new Error(`nPublic (${vk.nPublic}) != IC.length - 1 (${nPublic})`);
  }
  if (nPublic > MAX_PUBLIC_INPUTS) throw new Error(`nPublic ${nPublic} > ${MAX_PUBLIC_INPUTS}`);

  const encG1 = (pt: string[], lbl: string) =>
    parseFieldDecimal(pt[0], BN254_P, `${lbl}.x`) + parseFieldDecimal(pt[1], BN254_P, `${lbl}.y`);
  const encG2 = (pt: string[][], lbl: string) =>
    parseFieldDecimal(pt[0][1], BN254_P, `${lbl}.x_imag`) +
    parseFieldDecimal(pt[0][0], BN254_P, `${lbl}.x_real`) +
    parseFieldDecimal(pt[1][1], BN254_P, `${lbl}.y_imag`) +
    parseFieldDecimal(pt[1][0], BN254_P, `${lbl}.y_real`);

  return {
    protocol: "groth16",
    curve: "bn254",
    nPublic,
    alpha: encG1(vk.vk_alpha_1, "vk_alpha_1"),
    beta: encG2(vk.vk_beta_2, "vk_beta_2"),
    gamma: encG2(vk.vk_gamma_2, "vk_gamma_2"),
    delta: encG2(vk.vk_delta_2, "vk_delta_2"),
    ic: vk.IC.map((pt: string[], i: number) => encG1(pt, `IC[${i}]`)),
  };
}

export function validateAndConvertProof(proof: any) {
  const encG1 = (pt: string[], lbl: string) =>
    parseFieldDecimal(pt[0], BN254_P, `${lbl}.x`) + parseFieldDecimal(pt[1], BN254_P, `${lbl}.y`);
  const encG2 = (pt: string[][], lbl: string) =>
    parseFieldDecimal(pt[0][1], BN254_P, `${lbl}.x_imag`) +
    parseFieldDecimal(pt[0][0], BN254_P, `${lbl}.x_real`) +
    parseFieldDecimal(pt[1][1], BN254_P, `${lbl}.y_imag`) +
    parseFieldDecimal(pt[1][0], BN254_P, `${lbl}.y_real`);

  const a = encG1(proof.pi_a, "pi_a");
  const b = encG2(proof.pi_b, "pi_b");
  const c = encG1(proof.pi_c, "pi_c");
  return { a, b, c, packedHex: a + b + c };
}

export function encodePublicInputs(inputs: Array<string | number | bigint>): string[] {
  if (!Array.isArray(inputs)) throw new Error("Public inputs must be a JSON array");
  if (inputs.length > MAX_PUBLIC_INPUTS) throw new Error("Exceeds MaxPublicInputs (64)");
  return inputs.map((v, i) => parseFieldDecimal(v, BN254_R, `public[${i}]`));
}

